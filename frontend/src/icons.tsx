/**
 * The GNOME symbolic icon names the domain model already produces, mapped to
 * their Lucide equivalents. Keeping the mapping here means a status keeps the
 * property that matters: every state has a distinct shape, not only a colour.
 */
const ICONS: Record<string, LucideIcon> = {
  "object-select-symbolic": Check,
  "dialog-warning-symbolic": AlertTriangle,
  "dialog-error-symbolic": AlertCircle,
  "media-playback-pause-symbolic": Pause,
  "dialog-question-symbolic": HelpCircle,
  "dialog-information-symbolic": Info,
  "media-playback-start-symbolic": Play,
  "media-playback-stop-symbolic": Square,
  "media-skip-forward-symbolic": SkipForward,
  "content-loading-symbolic": Loader2,
  "network-offline-symbolic": WifiOff,
  "network-vpn-symbolic": Waypoints,
  "network-transmit-receive-symbolic": ArrowLeftRight,
  "network-server-symbolic": Server,
  "web-browser-symbolic": Globe,
  "document-open-recent-symbolic": History,
  "preferences-system-symbolic": Settings,
  "view-grid-symbolic": LayoutDashboard,
  "applications-system-symbolic": AppWindow,
  "package-x-generic-symbolic": Package,
  "security-high-symbolic": ShieldCheck,
  "channel-secure-symbolic": Lock,
  "list-add-symbolic": Plus,
  "document-edit-symbolic": FileEdit,
  "utilities-terminal-symbolic": Terminal,
  "system-run-symbolic": Play,
  "action-unavailable-symbolic": Unplug,
  "content-loading": Loader2,
};

export function symbolicIcon(name: string | undefined | null): LucideIcon {
  if (!name) return Circle;
  return ICONS[name] ?? Circle;
}

export function SymbolicIcon({
  name,
  size = 16,
  className,
  strokeWidth = 2,
}: {
  name: string | undefined | null;
  size?: number;
  className?: string;
  strokeWidth?: number;
}) {
  const Icon = symbolicIcon(name);
  return (
    <Icon
      size={size}
      className={className}
      strokeWidth={strokeWidth}
      aria-hidden="true"
    />
  );
}

